namespace WpfApp3
{
    /// <summary>
    /// Interaction logic for MainWindow.xaml
    /// </summary>
    public partial class MainWindow : Window
    {
        public MainWindow()
        {
            InitializeComponent();
        }

        private void Button_Click(object sender, RoutedEventArgs e)
        {
            try
            {
                double num1 = Convert.ToDouble(Num1TexBox.Text);
                double num2 = Convert.ToDouble(Num2TexBox.Text);
                double result = 0;

                Button button = (Button)sender;

                switch (button.Content)
                {
                    case "+":
                        result = num1 + num2;
                        break;
                    case "-":
                        result = num1 - num2;
                        break;
                    case "*":
                        result = num1 * num2;
                        break;
                    case "/":
                        result = num1 / num2;
                        break;
                }

                ResultText.Text = $"Результат {result} ";
            }

            catch (Exception ex) 
            {
                ResultText.Text = ex.Message;


            }
        }
    }
}